"""Minimal `geolens.yaml` manifest template helpers."""

from __future__ import annotations

from pathlib import Path

from geolens_cli import __version__


def minimal_manifest_text(manifest_version: str = "1") -> str:
    """Return a deterministic starter manifest that validates as ``manifest_version``."""

    if manifest_version == "2":
        return _V2_TEMPLATE.format(cli_version=__version__)
    return _V1_TEMPLATE


_V1_TEMPLATE = """manifest_version: "1"
catalog:
  title: Example GeoLens catalog
  description: Starter catalog generated by `geolens init`.
  organization: Example Organization
datasets:
  - key: sample-roads
    title: Sample roads
    description: Replace this entry with your dataset description.
    sources:
      - type: vector
        uri: ./data/roads.geojson
        format: geojson
    metadata:
      tags:
        - example
        - roads
      organization: Example Organization
      crs: EPSG:4326
      license: CC-BY-4.0
      attribution: Example Organization
      bbox: [-74.1, 40.5, -73.7, 40.9]
    publication:
      intent: draft
"""

# Version 2 is a preview. A local `uri` is uploaded by `geolens apply`, which
# fills in the `upload:` reference and the checksum.
_V2_TEMPLATE = """manifest_version: "2"
client:
  id: geolens-cli
  version: "{cli_version}"
catalog:
  title: Example GeoLens catalog
  description: Starter catalog generated by `geolens init`.
  organization: Example Organization
datasets:
  - key: sample-roads
    title: Sample roads
    description: Replace this entry with your dataset description.
    sources:
      - type: vector
        uri: ./data/roads.geojson
    metadata:
      tags:
        - example
        - roads
      license: CC-BY-4.0
    publication:
      intent: draft
    visibility: private
maps:
  - key: sample-map
    name: Sample map
    visibility: private
    layers:
      - key: roads
        dataset_key: sample-roads
"""


def write_minimal_manifest(
    path: Path, *, force: bool = False, manifest_version: str = "1"
) -> Path:
    """Write the starter manifest, refusing existing files unless forced."""

    if path.exists() and not force:
        raise FileExistsError(path)

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(minimal_manifest_text(manifest_version), encoding="utf-8")
    return path
