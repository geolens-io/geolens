@_tool
@_with_docs
def set_camera(
    map_id: str,
    center: Annotated[Optional[list[float]], Field(min_length=2, max_length=2)] = None,
    zoom: Annotated[Optional[float], Field(ge=0, le=24)] = None,
    pitch: Annotated[Optional[float], Field(ge=0, le=85)] = None,
    bearing: Annotated[Optional[float], Field(ge=-180, le=180)] = None,
) -> Any:
    """Set the view a map opens at. Only the arguments given change.
    {author}

    Args:
        map_id: A map this key created.
        center: [longitude, latitude] in WGS 84.
        zoom: Zoom level, 0-24.
        pitch: Tilt in degrees, 0-85.
        bearing: Rotation in degrees, -180 to 180.
    """
    view: dict[str, Any] = {}
    if center is not None:
        lng, lat = center
        if not (-180 <= lng <= 180 and -90 <= lat <= 90):
            raise ValueError("center must be [longitude, latitude] in WGS 84")
        view.update(center_lng=lng, center_lat=lat)
    for key, value in (("zoom", zoom), ("pitch", pitch), ("bearing", bearing)):
        if value is not None:
            view[key] = value
    if not view:
        raise ValueError("Give center, zoom, pitch or bearing")
    return _get_api().update_map_view(map_id, view)


@_tool
@_with_docs
def set_basemap(map_id: str, basemap: str) -> Any:
    """Change a map's basemap.
    {author}

    Args:
        map_id: A map this key created.
        basemap: Basemap id from the instance's basemap list, or "blank".
    """
    return _get_api().update_map_view(map_id, {"basemap_style": basemap})


def main() -> None:
    """Console-script entry point: run the server over stdio."""
    mcp.run()


if __name__ == "__main__":
    main()
