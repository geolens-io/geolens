"""One backfill run must use one model resolution (#1519 review, P1).

`backfill.py` stamps every row it writes with a model name it resolved once,
but `generate_embeddings_batch` re-read `EMBEDDING_MODEL` for each provider
call. An admin switching models while a run is in flight therefore got vectors
generated by model B stored under label A. Search on active-B skips them, and a
switch back to A consumes vectors that model never produced.

The same argument applies to `EMBEDDING_DIMS`: pinning the model while the
dimensions still re-read would call the provider with model A and B's
dimensions, which is an inconsistency neither half had on its own.

This divergence predates #1519. On `origin/main`, `backfill.py:109` already
reads the label once before the batch loop while `service.py:79` re-reads per
call, and the non-force path carries it identically. The force guard widened
the window rather than opening it, which is why both paths are covered here.

The switch is driven through the real `PersistentConfig.set`, from inside
`resolve_runtime_config` — the one await that `service.py` makes *after*
backfill has resolved its label and *before* the service re-reads the config
for the provider call. That is the actual interleaving, not a stubbed input.

Requirements:
  - Docker database must be running (docker compose up db)
  - Alembic migrations must be applied
"""

import uuid
from types import SimpleNamespace
from unittest.mock import AsyncMock, MagicMock

import pytest
from sqlalchemy import func, select, text

from app.core.persistent_config import EMBEDDING_DIMS, EMBEDDING_MODEL
from app.processing.embeddings import backfill as backfill_module
from app.processing.embeddings import service as service_module
from app.processing.embeddings.models import RecordEmbedding
from app.processing.embeddings.service import EmbeddingUnavailableError

from tests.factories import create_dataset, get_user_id

_MODEL_A = "pin-model-a"
_MODEL_B = "pin-model-b"
# 1536 matches the fixed vector column from migration 0012, so the row still
# inserts. The provider returns 1536 floats whatever it is told, which keeps
# the assertion on the argument it received rather than on what it returned.
_DIMS_A = 1536
_DIMS_B = 768


class _RecordingProvider:
    """Records the arguments each provider call received."""

    def __init__(self):
        self.calls: list[dict] = []
        # Stashed for the subclass that has to write config from inside a
        # provider call; `embed` is not handed a session.
        self._session = None

    async def resolve_runtime_config(self, session):
        self._session = session
        return {
            "default_model": "provider-fallback-model",
            "default_dims": 1536,
            "base_url": "http://embeddings.invalid",
        }

    async def embed(self, *, texts, model, dimensions, base_url, timeout):
        self.calls.append({"model": model, "dimensions": dimensions})
        return [[1.0] + [0.0] * 1535 for _ in texts]


class _StrictProvider(_RecordingProvider):
    """Rejects a (model, dimensions) pair the model does not support.

    Real embedding endpoints do this: asking a 768-dimension model for 1536
    is an error, not a silently truncated vector. Without that, a fake
    provider would happily accept the mismatched pair and the scenario would
    prove nothing.
    """

    _SUPPORTED = {_MODEL_A: _DIMS_A, _MODEL_B: _DIMS_B}

    async def embed(self, *, texts, model, dimensions, base_url, timeout):
        self.calls.append({"model": model, "dimensions": dimensions})
        if self._SUPPORTED.get(model) != dimensions:
            raise EmbeddingUnavailableError(
                f"model {model} does not support {dimensions} dimensions"
            )
        return [[1.0] + [0.0] * 1535 for _ in texts]


class _WidthProvider(_RecordingProvider):
    """Returns vectors of the width it was asked for.

    `_RecordingProvider` always answers 1536 regardless of `dimensions`, which
    is fine for the labelling scenarios but cannot express "the provider
    succeeded and the result does not fit the column". A real endpoint asked
    for 768 returns 768.
    """

    async def embed(self, *, texts, model, dimensions, base_url, timeout):
        self.calls.append({"model": model, "dimensions": dimensions})
        width = dimensions or 1536
        return [[1.0] + [0.0] * (width - 1) for _ in texts]


class _ExplodingProvider(_RecordingProvider):
    """Fails every call, so needing the provider at all is observable."""

    async def embed(self, *, texts, model, dimensions, base_url, timeout):
        self.calls.append({"model": model, "dimensions": dimensions})
        raise EmbeddingUnavailableError("no provider configured")


class _SwitchingProvider(_RecordingProvider):
    """Flips the live config from inside the first provider call.

    Covers the late window: a swap that lands once the run is already
    generating, after the snapshot has captured its own values and before the
    service would re-read them.

    The flip hangs on `embed` rather than on `resolve_runtime_config`, which is
    where it used to sit. fix(#1525) made `_snapshot_embedding_config` resolve
    the endpoint through `resolve_runtime_config`, so a flip there now lands
    INSIDE the capture window and the snapshot's comparison aborts the run.
    That is a real behaviour and it has its own coverage
    (`test_an_edit_inside_the_snapshot_window_aborts_the_run`), but it is not
    the scenario this file is about. `embed` is the first await after the
    snapshot completes on both paths, and it is where a run actually spends its
    time, so it is the more faithful place for an admin edit to land.
    """

    def __init__(self):
        super().__init__()
        self._switched = False

    async def embed(self, *, texts, model, dimensions, base_url, timeout):
        vectors = await super().embed(
            texts=texts,
            model=model,
            dimensions=dimensions,
            base_url=base_url,
            timeout=timeout,
        )
        if not self._switched:
            self._switched = True
            await EMBEDDING_MODEL.set(self._session, _MODEL_B)
            await EMBEDDING_DIMS.set(self._session, _DIMS_B)
        return vectors


async def _embedding_count(session) -> int:
    """Count every embedding row a force delete would clear."""
    return (
        await session.execute(select(func.count()).select_from(RecordEmbedding))
    ).scalar_one()


