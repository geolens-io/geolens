"""Let a dataset keep several previous versions.

A kept version's table, the time it was kept, its size and the kept data's
own refresh time move from ``catalog.datasets`` onto that version's
``catalog.dataset_versions`` row, so a dataset can keep one table per
version. The one previous version a dataset keeps today is copied onto its
version row, under the table name it already has; no table is renamed. A
version row missing for it is written from what the dataset recorded.

The downgrade refuses while any dataset keeps more than one version, since
the earlier schema holds one. Otherwise it copies each kept version back
onto its dataset and renames its table to the single name the earlier code
expects. It looks in the dataset's own data schema first, then in another
data schema where no dataset uses the name. A kept version whose table it
cannot find is not copied back, and the downgrade notes it.

Hand-written, not autogenerated: autogenerate against a database carrying the
enterprise overlay emits that overlay's SAML columns as core DDL.

Revision ID: 0088_dataset_kept_versions
Revises: 0087_publish_api_keys
Create Date: 2026-10-21
"""

