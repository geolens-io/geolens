import sqlalchemy as sa
from alembic import op

revision: str = "0080_timestamptz_tile_text_utc"
down_revision: Union[str, None] = "0079_dataset_data_revision"
branch_labels: Union[str, Sequence[str], None] = None
depends_on: Union[str, Sequence[str], None] = None

_LOCK_TIMEOUT = "SET LOCAL lock_timeout = '5s'"


def upgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    op.execute(
        sa.text(
            "UPDATE catalog.datasets "
            "SET tile_cache_version = coalesce(tile_cache_version, 1) + 1 "
            "WHERE column_info @> "
            """'[{"type": "timestamp with time zone"}]'::jsonb"""
        )
    )


