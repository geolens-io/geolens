"""Roll the tile version of every dataset with a timestamptz column.

Vector tiles now write timestamptz properties as UTC text instead of the
database session's local form. Tile cache keys and tile URLs carry
``tile_cache_version``, so rolling it keeps the tile cache, browsers and
CDNs from serving the old text after an upgrade. Datasets without such a
column tile the same bytes and keep their version.

Hand-written, not autogenerated: a data update has nothing to autogenerate.

Revision ID: 0080_timestamptz_tile_text_utc
Revises: 0079_dataset_data_revision
Create Date: 2026-10-08
"""

